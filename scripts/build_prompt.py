def do_list():
    print("可用模板（id -> 描述）：\n")
    for k, (desc, _) in TEMPLATES.items():
        print(f"  {k:8s} {desc}")


def fill(text, goal, scope, verify, constraint):
    """把用户提供的片段填进对应占位符，其余【…】保留手动补全。"""
    if goal:
        # 只替换"问题/核心问题"类槽位；"最终可用方案/状态"语义不同，保留为占位符
        for ph in ["【具体问题】", "【当前核心问题】", "【某个方案 / 某个模块怎么做】", "【某个 bug】"]:
            text = text.replace(ph, goal, 1)
    if scope:
        for ph in ["【范围 B】", "【无关范围】", "【范围 A】"]:
            text = text.replace(ph, scope, 1)
    if verify:
        for ph in ["【测试 / 最小验证步骤 / 验收标准】", "【测试 / 最小验证闭环】"]:
            text = text.replace(ph, verify, 1)
    if constraint:
        text = text + f"\n（补充约束：{constraint}）"
    return text


def do_gen(tid, goal, scope, verify, constraint):
    if tid not in TEMPLATES:
        print(f"未知模板 id：{tid}\n用 `build_prompt.py list` 查看可用模板。", file=sys.stderr)
        sys.exit(2)
    desc, tpl = TEMPLATES[tid]
    out = fill(tpl, goal, scope, verify, constraint)
    print(f"# {desc}  （id={tid}）\n")
    print(out)
    if "【" in out:
        print("\n— 提示：文本中剩余的 【…】 需你结合真实任务手动补全。")


def main():
    p = argparse.ArgumentParser(description="Codex 协作方法论 · 提示词生成器")
    sub = p.add_subparsers(dest="cmd")

    sub.add_parser("list", help="列出所有可用模板")

    g = sub.add_parser("gen", help="生成结构化提示词")
    g.add_argument("id", help="模板 id，如 qi2 / shu09 / core")
    g.add_argument("--goal", help="填入口标/具体问题（替换【具体问题】等）")
    g.add_argument("--scope", help="填入范围约束（替换【范围 B】/【无关范围】等）")
    g.add_argument("--verify", help="填入验证方式（替换【测试 / …】）")
    g.add_argument("--constraint", help="额外约束，追加到结尾")

    args = p.parse_args()
    if args.cmd == "list" or args.cmd is None:
        do_list()
    elif args.cmd == "gen":
        do_gen(args.id, args.goal, args.scope, args.verify, args.constraint)


if __name__ == "__main__":
    main()
